package cn.ncii.lottie.web;

/** Values exposed by the skeleton group in the plugin setting definition. */
public class LottieSkeletonSettings {

    private Boolean skeletonEnabled = true;
    private Boolean skeletonLoaderEnabled = true;
    private Boolean skeletonBackgroundEnabled = true;
    private String skeletonBackgroundColor = "#f3f4f6";
    private Boolean skeletonBorderEnabled = true;
    private String skeletonBorderColor = "#d7dbe0";
    private String skeletonAccentColor = "#6b7280";
    private Integer skeletonBorderRadius = 8;
    private Integer skeletonBackgroundOpacity = 100;

    public Boolean getSkeletonEnabled() {
        return skeletonEnabled;
    }

    public void setSkeletonEnabled(Boolean skeletonEnabled) {
        this.skeletonEnabled = skeletonEnabled;
    }

    public Boolean getSkeletonLoaderEnabled() {
        return skeletonLoaderEnabled;
    }

    public void setSkeletonLoaderEnabled(Boolean skeletonLoaderEnabled) {
        this.skeletonLoaderEnabled = skeletonLoaderEnabled;
    }

    public Boolean getSkeletonBackgroundEnabled() {
        return skeletonBackgroundEnabled;
    }

    public void setSkeletonBackgroundEnabled(Boolean skeletonBackgroundEnabled) {
        this.skeletonBackgroundEnabled = skeletonBackgroundEnabled;
    }

    public String getSkeletonBackgroundColor() {
        return skeletonBackgroundColor;
    }

    public void setSkeletonBackgroundColor(String skeletonBackgroundColor) {
        this.skeletonBackgroundColor = skeletonBackgroundColor;
    }

    public Boolean getSkeletonBorderEnabled() {
        return skeletonBorderEnabled;
    }

    public void setSkeletonBorderEnabled(Boolean skeletonBorderEnabled) {
        this.skeletonBorderEnabled = skeletonBorderEnabled;
    }

    public String getSkeletonBorderColor() {
        return skeletonBorderColor;
    }

    public void setSkeletonBorderColor(String skeletonBorderColor) {
        this.skeletonBorderColor = skeletonBorderColor;
    }

    public String getSkeletonAccentColor() {
        return skeletonAccentColor;
    }

    public void setSkeletonAccentColor(String skeletonAccentColor) {
        this.skeletonAccentColor = skeletonAccentColor;
    }

    public Integer getSkeletonBorderRadius() {
        return skeletonBorderRadius;
    }

    public void setSkeletonBorderRadius(Integer skeletonBorderRadius) {
        this.skeletonBorderRadius = skeletonBorderRadius;
    }

    public Integer getSkeletonBackgroundOpacity() {
        return skeletonBackgroundOpacity;
    }

    public void setSkeletonBackgroundOpacity(Integer skeletonBackgroundOpacity) {
        this.skeletonBackgroundOpacity = skeletonBackgroundOpacity;
    }
}
